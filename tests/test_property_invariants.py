"""Property/fuzz invariants over randomly generated LEGAL Hold'em states.

States are generated by playing random legal actions through the real
engine (``poker_alpha.holdem.engine``), so every fuzzed state is legal by
construction — validation is never weakened to accommodate the generator.
Deterministic seeds; no hypothesis dependency.
"""

from __future__ import annotations

import math
import random

import numpy as np
import pytest

from poker_alpha.decision import DecisionConfig, recommend_action
from poker_alpha.holdem import (Action, SimulationStateAdapter, TableConfig,
                                apply_action, cards_needed, deal_board_random,
                                legal_actions, start_hand, validate)
from poker_alpha.holdem.adapters import ManualStateAdapter, observed_to_dict
from poker_alpha.pipeline import load_solver
from poker_alpha.solver_config import RELEASE_STRATEGY

N_STATES = 40
CFG = DecisionConfig(equity_simulations=80, rollout_simulations=80)


def random_states(seed: int, n: int = N_STATES):
    """Legal observed states harvested from random self-play (HU and
    3-max), snapshotted whenever seat 0 is to act."""
    rng = random.Random(seed)
    out = []
    while len(out) < n:
        players = rng.choice((2, 2, 3))
        stacks = [rng.choice((40, 100, 200)) * 2 for _ in range(players)]
        deck = list(range(52))
        rng.shuffle(deck)
        holes = [tuple(sorted((deck.pop(), deck.pop())))
                 for _ in range(players)]
        state = start_hand(stacks, rng.randrange(players),
                           TableConfig(small_blind=1, big_blind=2),
                           hole_cards=holes)
        nprng = np.random.default_rng(rng.getrandbits(32))
        guard = 0
        while guard < 60:
            guard += 1
            if state.actor is None:
                if cards_needed(state):
                    state = deal_board_random(state, nprng)
                    continue
                break
            if state.actor == 0 and state.seats[0].hole_cards:
                obs = SimulationStateAdapter.observe(state, hero_seat=0,
                                                     chip_unit=0.5)
                out.append(obs)
                if len(out) >= n:
                    return out
            la = legal_actions(state)
            opts = []
            if la.can_fold:
                opts.append(Action.fold())
            if la.can_check:
                opts.append(Action.check())
            if la.call_amount > 0:
                opts.append(Action.call())
            if la.can_raise:
                lo, hi = la.min_raise_to, la.max_raise_to
                to = rng.choice((lo, min(hi, lo * 2), hi))
                opts.append(Action.raise_to(to) if not la.is_bet
                            else Action.bet(to))
            state = apply_action(state, rng.choice(opts))
    return out


@pytest.fixture(scope="module")
def states():
    return random_states(seed=2026)


@pytest.fixture(scope="module")
def solver():
    return load_solver(RELEASE_STRATEGY)


def test_generated_states_are_legal(states):
    assert len(states) == N_STATES
    for obs in states:
        errs = [i for i in validate(obs) if i.severity == "error"]
        assert not errs, (obs.describe(), errs)
        cards = list(obs.hero_cards or ()) + list(obs.board)
        assert len(set(cards)) == len(cards)           # no duplicates
        assert all((s.stack or 0) >= 0 for s in obs.seats)
        assert (obs.pot or 0) >= 0


def test_report_invariants_over_fuzzed_states(states, solver):
    for obs in states[:20]:
        rep = recommend_action(obs, config=CFG)
        reps = (rep, recommend_action(obs, config=DecisionConfig(
            equity_simulations=80, rollout_simulations=80,
            solver=solver if not hasattr(solver, "code") else None)))
        for r in reps:
            # frequencies: finite, nonnegative, and solver mixes sum to 1
            for c in r.candidates:
                if c.probability is not None:
                    assert math.isfinite(c.probability)
                    assert -1e-9 <= c.probability <= 1 + 1e-9
                assert c.amount_to >= -1e-9 and c.added >= -1e-9
            if "solver" in r.method or "abstraction" in r.method:
                total = sum(c.probability or 0 for c in r.candidates)
                assert abs(total - 1) < 1e-6
            info = r.details.get("solver", {})
            # a rejected gate must never masquerade as a used solver
            if info.get("confidence") in ("rejected",):
                assert not info.get("used")
                assert "solver" not in r.method
            # refusals never carry recommendations
            if r.method == "none" and r.details.get("refusal_codes"):
                assert r.recommended is None and not r.candidates


def test_refusal_states_never_recommend(states):
    from dataclasses import replace

    obs = states[0]
    not_turn = replace(obs, actor=(obs.hero_seat + 1) % obs.num_seats)
    r = recommend_action(not_turn, config=CFG)
    assert r.recommended is None and r.candidates == ()
    assert "NOT_HERO_TURN" in r.details.get("refusal_codes", ())


def test_determinism_same_input_same_seed(states, solver):
    obs = states[1]
    cfg = DecisionConfig(equity_simulations=120, rollout_simulations=120,
                         seed=7,
                         solver=None if hasattr(solver, "code") else solver)
    a = recommend_action(obs, config=cfg)
    b = recommend_action(obs, config=cfg)
    assert a.recommended == b.recommended
    assert a.recommended_mix == b.recommended_mix
    assert [(c.label, c.ev_bb, c.ev_se_bb) for c in a.candidates] == \
        [(c.label, c.ev_bb, c.ev_se_bb) for c in b.candidates]
    assert a.details.get("rollout_paired_differences") == \
        b.details.get("rollout_paired_differences")


def test_observed_state_serialization_round_trip(states):
    for obs in states[:10]:
        d = observed_to_dict(obs)
        back = ManualStateAdapter.from_dict(d)
        assert back.hero_cards == obs.hero_cards
        assert back.board == obs.board
        assert back.pot == pytest.approx(obs.pot)
        assert back.street == obs.street
        assert [s.stack for s in back.seats] == \
            pytest.approx([s.stack for s in obs.seats])
        assert back.amount_to_call == pytest.approx(obs.amount_to_call)


@pytest.mark.slow
def test_api_matches_direct_python_semantics(states, solver):
    """The API result for a fuzzed state carries the same semantics as the
    direct Python call (same recommended action, mix, solver state)."""
    fastapi = pytest.importorskip("fastapi")  # noqa: F841
    from fastapi.testclient import TestClient

    from poker_alpha.api.server import create_app
    from poker_alpha.ui.viewmodel import recommendation_vm

    client = TestClient(create_app())
    for obs in states[:5]:
        d = observed_to_dict(obs)
        resp = client.post("/analyze", json={
            "state": d, "settings": {"equity_simulations": 80,
                                     "rollout_simulations": 80, "seed": 0,
                                     "use_solver": True}})
        assert resp.status_code == 200, resp.text
        api = resp.json()
        direct = recommend_action(
            ManualStateAdapter.from_dict(d),
            config=DecisionConfig(equity_simulations=80,
                                  rollout_simulations=80, seed=0,
                                  solver=None if hasattr(solver, "code")
                                  else solver))
        vm = recommendation_vm(direct)
        assert api["recommended"] == direct.recommended
        assert api["solver_state"] == vm.solver_state
        assert api["ev_is_decision_basis"] == vm.ev_is_decision_basis
        api_mix = {a["label"]: a["frequency"] for a in api["actions"]
                   if a["frequency"]}
        direct_mix = {k: v for k, v in direct.recommended_mix.items() if v}
        for k, v in direct_mix.items():
            assert api_mix.get(k) == pytest.approx(v, abs=1e-9)


@pytest.mark.slow
def test_packaged_engine_matches_repo_engine():
    """The frozen engine (when built locally) gives the same semantics as
    the in-repo engine for a fixture case. Skipped when no bundle exists
    (CI does not build it)."""
    import json
    import subprocess
    import time
    import urllib.request
    from pathlib import Path

    root = Path(__file__).resolve().parents[1]
    binary = root / "packaging" / "dist" / "pokeralpha-engine" / "pokeralpha-engine"
    if not binary.exists():
        pytest.skip("frozen engine not built (packaging/dist missing)")
    from poker_alpha.demo_spots import DEMO_SPOTS

    state = DEMO_SPOTS["River, checked to hero — solver accepted"]
    proc = subprocess.Popen([str(binary), "--port", "0"],
                            stdout=subprocess.PIPE,
                            stderr=subprocess.DEVNULL, text=True)
    try:
        port = None
        t0 = time.time()
        while time.time() - t0 < 60:
            line = proc.stdout.readline()
            if line.startswith("POKERALPHA_API_PORT="):
                port = int(line.split("=")[1])
                break
        assert port
        base = f"http://127.0.0.1:{port}"
        t0 = time.time()
        while time.time() - t0 < 60:
            try:
                urllib.request.urlopen(base + "/health", timeout=1)
                break
            except Exception:
                time.sleep(0.3)
        body = json.dumps({"state": state,
                           "settings": {"equity_simulations": 200,
                                        "rollout_simulations": 200,
                                        "seed": 0, "use_solver": True}}).encode()
        req = urllib.request.Request(base + "/analyze", body,
                                     {"Content-Type": "application/json"})
        frozen = json.loads(urllib.request.urlopen(req, timeout=120).read())
    finally:
        proc.terminate()
        proc.wait(timeout=10)
    from poker_alpha.pipeline import analyze, observe_manual

    direct = analyze(observe_manual(state),
                     config=DecisionConfig(equity_simulations=200,
                                           rollout_simulations=200, seed=0),
                     solver=load_solver(RELEASE_STRATEGY))
    assert frozen["recommended"] == direct.recommended
    assert frozen["solver_state"] == "ACCEPTED"
    frozen_mix = {a["label"]: a["frequency"] for a in frozen["actions"]}
    for k, v in direct.recommended_mix.items():
        assert frozen_mix.get(k) == pytest.approx(v, abs=1e-9)
