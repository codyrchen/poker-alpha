TREE_FRACTIONS = (0.33, 0.75, 1.5)


# ---------------------------------------------------------------------------
# legal state generation (engine playouts, reproducible)
# ---------------------------------------------------------------------------

def sample_states(n: int, seed: int = 0,
                  stacks_bb: Tuple[int, ...] = (100, 100)) -> List[dict]:
    """Legal HU observed-state dicts harvested from random self-play at
    ~100bb (the depth the release abstraction covers), snapshotted at
    hero decision points. Deterministic in ``seed``."""
    rng = random.Random(seed)
    out: List[dict] = []
    while len(out) < n:
        chips = [s * 2 for s in stacks_bb]       # sb=1 bb=2 chip units
        deck = list(range(52))
        rng.shuffle(deck)
        holes = [tuple(sorted((deck.pop(), deck.pop()))) for _ in chips]
        state = start_hand(chips, rng.randrange(2),
                           TableConfig(small_blind=1, big_blind=2),
                           hole_cards=holes)
        nprng = np.random.default_rng(rng.getrandbits(32))
        for _ in range(40):
            if state.actor is None:
                if cards_needed(state):
                    state = deal_board_random(state, nprng)
                    continue
                break
            if state.actor == 0:
                obs = SimulationStateAdapter.observe(state, hero_seat=0,
                                                     chip_unit=0.5)
                out.append(observed_to_dict(obs))
                if len(out) >= n:
                    return out
            la = legal_actions(state)
            opts = []
            if la.can_check:
                opts += [Action.check()] * 2
            if la.call_amount > 0:
                opts += [Action.call()] * 2
            if la.can_fold:
                opts.append(Action.fold())
            if la.can_raise:
                lo, hi = la.min_raise_to, la.max_raise_to
                mid = min(hi, max(lo, int(lo * rng.uniform(1.0, 3.0))))
                opts.append(Action.bet(mid) if la.is_bet
                            else Action.raise_to(mid))
            state = apply_action(state, rng.choice(opts))
    return out


# ---------------------------------------------------------------------------
# scoring
# ---------------------------------------------------------------------------

@dataclass
class StateScore:
    state: dict
    street: str
    spr: Optional[float]
    facing_bet_bb: float
    pot_bb: float
    gate: str                            # ACCEPTED / LOW CONFIDENCE / REJECTED / OFF
    gate_reasons: List[str]
    method: str
    top_action: Optional[str]
    mix: Dict[str, float]
    # separate objective components (never combined):
    gate_rejected: bool = False
    seed_disagreement: Optional[float] = None
    visits: Optional[float] = None
    translation_distance: Optional[float] = None
    local_sensitivity: Optional[float] = None
    model_sensitivity: Optional[float] = None


def _distribution(report) -> Dict[str, float]:
    mix = dict(report.recommended_mix or {})
    if mix:
        return mix
    return {c.label: c.probability for c in report.candidates if c.probability}


def _translation_distance(state: dict) -> Optional[float]:
    """Relative distance of the faced bet from the nearest trained
    pot-fraction size. None when not facing a bet."""
    hero = state["hero_seat"]
    bets = [s.get("bet", 0.0) for s in state["seats"]]
    facing = max(b for i, b in enumerate(bets) if i != hero) - bets[hero]
    if facing <= 0:
        return None
    pot_before = state["pot"] - sum(bets)
    if pot_before <= 0:
        pot_before = max(state["pot"], 1e-9)
    frac = facing / pot_before
    return min(abs(frac - f) / f for f in TREE_FRACTIONS)


def score_state(state: dict, solver, cfg: DecisionConfig,
                models: Tuple[str, ...] = ("regular", "nit",
                                           "calling_station", "maniac"),
                ) -> Optional[StateScore]:
    obs = observe_manual(state)
    rep = analyze(obs, config=cfg, solver=solver)
    if rep.method == "none":                 # refusal: not a solver weakness
        return None
    info = (rep.details or {}).get("solver", {})
    gate = solver_state(rep)
    dist = _distribution(rep)
    s = obs.state
    hero = s.hero
    facing = s.amount_to_call or 0.0
    score = StateScore(
        state=state, street=s.street.name.title(),
        spr=round(s.spr, 2) if s.spr is not None else None,
        facing_bet_bb=round(facing / s.big_blind, 2),
        pot_bb=round((s.pot or 0) / s.big_blind, 2),
        gate=gate, gate_reasons=list(info.get("reasons", ())),
        method=rep.method,
        top_action=max(dist, key=dist.get) if dist else rep.recommended,
        mix={k: round(v, 4) for k, v in
             sorted(dist.items(), key=lambda x: -x[1])[:5]},
        gate_rejected=gate == "REJECTED",
        seed_disagreement=info.get("seed_disagreement"),
        visits=info.get("visits"),
        translation_distance=_translation_distance(state),
    )
    # local sensitivity: ±10% perturbation of the faced bet (or pot)
    try:
        if facing > 0:
            v = max(b for i, b in enumerate(
                [st.get("bet", 0.0) for st in state["seats"]])
                if i != state["hero_seat"])
            pert = apply_whatif(state, "villain_bet", round(v * 1.1, 2))
        else:
            pert = apply_whatif(state, "pot", round(state["pot"] * 1.1, 2))
        rep2 = analyze(observe_manual(pert), config=cfg, solver=solver)
        score.local_sensitivity = round(_tv(dist, _distribution(rep2)), 4)
    except (WhatIfError, ValueError):
        pass
    # model sensitivity: max TV across archetypes
    from dataclasses import replace as _rep

    base_dist = dist
    worst = 0.0
    for m in models[1:]:
        repm = analyze(obs, config=_rep(cfg, default_model=m), solver=solver)
        worst = max(worst, _tv(base_dist, _distribution(repm)))
    score.model_sensitivity = round(worst, 4)
    return score


