"""Solver Red Team: automated search for states where PokerAlpha is
fragile.

States are generated by playing RANDOM LEGAL ACTIONS through the real
Hold'em engine (never by inventing tuples and weakening validators), then
scored on SEPARATE, transparent objective components:

    gate_rejected          the confidence gate withheld the strategy
    seed_disagreement      cross-seed policy disagreement signal at the key
    low_visits             training-visit scarcity at the key
    translation_distance   relative distance of the faced bet from the
                           nearest trained pot-fraction size (33/75/150%)
    local_sensitivity      total-variation policy change under a ±10%
                           perturbation of the faced bet / pot
    model_sensitivity      max TV across the four behavior archetypes

No single combined score is produced. Finding weaknesses is the point:
the output feeds the public failure explorer and the research backlog.

Statistical discipline: searching many random states WILL surface extreme
values by chance. Scores here are DISCOVERY results; anything promoted to
a claim must be re-run with independent seeds/samples (see
docs/red_team.md).
"""

from __future__ import annotations

