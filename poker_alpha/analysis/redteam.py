def run_search(n_states: int = 200, seed: int = 0,
               config: Optional[DecisionConfig] = None,
               solver=None, progress=None) -> dict:
    cfg = config or DecisionConfig(equity_simulations=100,
                                   rollout_simulations=100)
    t0 = time.time()
    states = sample_states(n_states, seed=seed)
    scores: List[StateScore] = []
    for i, st in enumerate(states):
        sc = score_state(st, solver, cfg)
        if sc is not None:
            scores.append(sc)
        if progress:
            progress(i, len(states))

    def top(attr, k=10, reverse=True):
        vals = [s for s in scores if getattr(s, attr) is not None]
        vals.sort(key=lambda s: getattr(s, attr), reverse=reverse)
        return [asdict(s) for s in vals[:k]]

    rejected = [asdict(s) for s in scores if s.gate_rejected][:20]
    report = {
        "format": "pokeralpha.redteam/v1",
        "seed": seed, "n_states_sampled": n_states,
        "n_states_scored": len(scores),
        "config": {"equity_simulations": cfg.equity_simulations,
                   "rollout_simulations": cfg.rollout_simulations,
                   "seed": cfg.seed},
        "wall_seconds": round(time.time() - t0, 1),
        "discipline": ("DISCOVERY results from random search; extreme "
                       "values must be replicated with independent "
                       "seeds/samples before becoming claims"),
        "leaderboards": {
            "rejected_states": rejected,
            "seed_disagreement": top("seed_disagreement"),
            "local_sensitivity": top("local_sensitivity"),
            "model_sensitivity": top("model_sensitivity"),
            "translation_distance": top("translation_distance"),
            "low_visits": top("visits", reverse=False),
        },
        "summary": summarize_scores(scores),
        "clusters": cluster_failures(scores),
    }
    return report


def summarize_scores(scores: List[StateScore]) -> dict:
    from collections import Counter

    gates = Counter(s.gate for s in scores)
    reasons = Counter(r for s in scores for r in s.gate_reasons)
    return {
        "gate_counts": dict(gates),
        "gate_reason_counts": dict(reasons),
        "sampling": ("random legal self-play snapshots at hero decision "
                     "points, ~100bb HU; NOT the natural distribution of "
                     "human play"),
    }


def _spr_bucket(spr: Optional[float]) -> str:
    if spr is None:
        return "unknown"
    if spr < 1:
        return "spr<1"
    if spr < 4:
        return "spr 1-4"
    if spr < 13:
        return "spr 4-13"
    return "spr>13"


def _bet_bucket(bet_bb: float, pot_bb: float) -> str:
    if bet_bb <= 0:
        return "no bet"
    frac = bet_bb / max(pot_bb - bet_bb, 1e-9)
    if frac < 0.5:
        return "bet<50%pot"
    if frac < 1.0:
        return "bet 50-100%pot"
    return "bet>pot"


def cluster_failures(scores: List[StateScore],
                     min_cluster: int = 3) -> List[dict]:
    """Interpretable rule-based clustering of flagged states by
    (street, SPR bucket, faced-bet bucket). A state is flagged when the
    gate rejected it OR local sensitivity >= 0.3 OR model sensitivity
    >= 0.3. No causal interpretation is attached."""
    from collections import defaultdict

    flagged = [s for s in scores if s.gate_rejected
               or (s.local_sensitivity or 0) >= 0.3
               or (s.model_sensitivity or 0) >= 0.3]
    groups = defaultdict(list)
    for s in flagged:
        groups[(s.street, _spr_bucket(s.spr),
                _bet_bucket(s.facing_bet_bb, s.pot_bb))].append(s)
    out = []
    for (street, spr, bet), members in sorted(groups.items(),
                                              key=lambda kv: -len(kv[1])):
        if len(members) < min_cluster:
            continue
        from collections import Counter

        reasons = Counter(r for m in members for r in m.gate_reasons)
        out.append({
            "street": street, "spr": spr, "bet": bet,
            "count": len(members),
            "signals": {
                "gate_rejected": sum(m.gate_rejected for m in members),
                "mean_local_sensitivity": round(float(np.mean(
                    [m.local_sensitivity or 0 for m in members])), 3),
                "mean_model_sensitivity": round(float(np.mean(
                    [m.model_sensitivity or 0 for m in members])), 3),
                "top_gate_reasons": reasons.most_common(3),
            },
            "note": "descriptive grouping, not a causal diagnosis",
        })
    return out


def research_backlog(report: dict) -> List[dict]:
    """Deterministic rule-based next-experiment suggestions from measured
    clusters. No free-form generation."""
    out = []
    for c in report.get("clusters", []):
        sig = c["signals"]
        reasons = dict(sig.get("top_gate_reasons", []))
        if reasons.get("HIGH_SEED_DISAGREEMENT", 0) >= 2 and c["count"] >= 5:
            out.append({
                "cluster": f"{c['street']}/{c['spr']}/{c['bet']}",
                "candidate": "abstraction-collision investigation",
                "rule": "HIGH_SEED_DISAGREEMENT in >=2 members and >=5 states",
            })
        if reasons.get("LOW_VISIT_COUNT", 0) >= 2:
            out.append({
                "cluster": f"{c['street']}/{c['spr']}/{c['bet']}",
                "candidate": "training-coverage investigation",
                "rule": "LOW_VISIT_COUNT in >=2 members",
            })
        if sig["mean_model_sensitivity"] >= 0.3:
            out.append({
                "cluster": f"{c['street']}/{c['spr']}/{c['bet']}",
                "candidate": "opponent-model robustness investigation",
                "rule": "mean model sensitivity >= 0.3",
            })
    return out


def save_report(report: dict, path) -> None:
    from pathlib import Path

    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(report, indent=1, default=str))


